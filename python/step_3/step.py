# ------------------------------------------------------------
# 2. ИНДЕКСАЦИЯ — доступ к символам по номеру позиции
# ------------------------------------------------------------
#  P  y  t  h  o  n
#  0  1  2  3  4  5   — прямые индексы
# -6 -5 -4 -3 -2 -1   — обратные индексы

word = "Python"
print("\n=== Индексация ===")
print(word[0])    # P — первый символ
print(word[5])    # n — последний
print(word[-1])   # n — последний (обратный индекс)
print(word[-2])   # o


# ------------------------------------------------------------
# 3. СРЕЗЫ — вырезаем часть строки [start:stop:step]
# ------------------------------------------------------------
# stop — НЕ включается в результат
text = "Hello, World!"

print("\n=== Срезы ===")
print(text[0:5])    # Hello
print(text[7:])     # World!
print(text[:5])     # Hello
print(text[::2])    # Hlo ol!  — каждый второй символ
print(text[::-1])   # !dlroW ,olleH — строка наоборот


# ------------------------------------------------------------
# 4. МЕТОДЫ СТРОК
# ------------------------------------------------------------
s = "  hello, world!  "

print("\n=== Методы ===")
print(s.strip())          # убирает пробелы по краям
print(s.strip().upper())  # HELLO, WORLD!
print(s.strip().lower())  # hello, world!

greeting = "Hello, World!"
print(greeting.replace("World", "Python"))  # Hello, Python!
print(greeting.count("l"))                  # 3 — кол-во вхождений
print(greeting.startswith("Hello"))         # True
print(greeting.endswith("!"))               # True
print(greeting.find("World"))               # 7 — индекс начала
print(greeting.split(", "))                 # ['Hello', 'World!']

# Объединение списка в строку
words = ["Python", "это", "круто"]
result = " ".join(words)
print(result)  # Python это круто


# ------------------------------------------------------------
# 5. F-СТРОКИ — форматирование (Python 3.6+)
# ------------------------------------------------------------
# Самый современный и удобный способ вставлять переменные

print("\n=== F-строки ===")
first_name = "Алексей"
age = 25
height = 1.82

print(f"Меня зовут {first_name}, мне {age} лет.")
print(f"Рост: {height:.1f} м")   # .1f — 1 знак после запятой
print(f"Сумма 5 + 3 = {5 + 3}")  # можно писать выражения

# Выравнивание текста
product = "Яблоко"
price = 45.5
print(f"{product:<10} {price:>8.2f} руб.")  # выравнивание по колонкам


# ------------------------------------------------------------
