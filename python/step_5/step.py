# ------------------------------------------------------------
# 1. ЦИКЛ WHILE — повторяет блок, пока условие True
# ------------------------------------------------------------
print("=== while ===")

count = 0
while count < 5:
    print(f"count = {count}")
    count += 1          # ОБЯЗАТЕЛЬНО изменять условие, иначе бесконечный цикл!

print("Цикл завершён\n")

# Типичный паттерн: countdown
n = 3
while n > 0:
    print(f"Осталось: {n}")
    n -= 1
print("Поехали!")


# ------------------------------------------------------------
# 2. ЦИКЛ FOR — перебирает элементы последовательности
# ------------------------------------------------------------
print("\n=== for ===")

# range(stop)           → 0, 1, 2, ..., stop-1
# range(start, stop)    → start, ..., stop-1
# range(start, stop, step)

for i in range(5):
    print(i, end=" ")   # end=" " — печать в одну строку
print()

for i in range(1, 11):
    print(i, end=" ")
print()

for i in range(0, 20, 3):  # шаг 3
    print(i, end=" ")
print()

for i in range(10, 0, -2):  # обратный отсчёт
    print(i, end=" ")
print()

# for по строке — перебирает символы
for char in "Python":
    print(char, end="-")
print()

# for по списку
colors = ["красный", "зелёный", "синий"]
for color in colors:
    print(color)


# ------------------------------------------------------------
# 3. BREAK — выход из цикла
# ------------------------------------------------------------
print("\n=== break ===")

# Найдём первое число, делящееся на 7
for num in range(1, 100):
    if num % 7 == 0:
        print(f"Первое кратное 7: {num}")
        break           # сразу выходим, не продолжаем перебор


# ------------------------------------------------------------
# 4. CONTINUE — пропустить текущую итерацию
# ------------------------------------------------------------
print("\n=== continue ===")

# Напечатать только нечётные числа от 1 до 10
for i in range(1, 11):
    if i % 2 == 0:
        continue        # пропускаем чётные
    print(i, end=" ")
print()


# ------------------------------------------------------------
# 5. ELSE В ЦИКЛЕ — выполняется, если цикл НЕ прервался через break
# ------------------------------------------------------------
print("\n=== else ===")

# Проверка числа на простоту
number = 17
for d in range(2, number):
    if number % d == 0:
        print(f"{number} — составное")
        break
else:
    print(f"{number} — простое число")   # <-- выполнится


# ------------------------------------------------------------
# 6. ВЛОЖЕННЫЕ ЦИКЛЫ — таблица умножения
# ------------------------------------------------------------
print("\n=== Вложенные циклы (таблица 3×3) ===")

for row in range(1, 4):
    for col in range(1, 4):
        print(f"{row * col:3}", end="")  # :3 — ширина 3 символа
    print()     # перенос строки после каждой строки таблицы


# ------------------------------------------------------------
# 7. ENUMERATE — индекс + значение одновременно
# ------------------------------------------------------------
print("\n=== enumerate ===")

fruits = ["яблоко", "банан", "вишня"]
for index, fruit in enumerate(fruits):
    print(f"{index}: {fruit}")

for index, fruit in enumerate(fruits, start=1):  # нумерация с 1
    print(f"{index}. {fruit}")


# ------------------------------------------------------------
# 8. ZIP — перебираем два списка параллельно
# ------------------------------------------------------------
print("\n=== zip ===")

names = ["Анна", "Борис", "Вера"]
scores = [95, 82, 78]

for name, score in zip(names, scores):
    print(f"{name}: {score} очков")


