# ------------------------------------------------------------
# 1. СЛОВАРЬ — коллекция пар "ключ: значение"
# ------------------------------------------------------------
# Ключи должны быть уникальными и неизменяемыми (str, int, tuple)
# Значения могут быть любыми

print("=== Создание словаря ===")

empty_d:dict = {} #  dict() - dictionary
person = {
    "name": "Алексей",
    "age": 25,
    "city": "Москва",
    "is_student": True
}

# Создание через dict()
settings = dict(theme="dark", language="ru", font_size=14)

print(person)
print(settings)
print(len(person))     # 4 — количество пар


# ------------------------------------------------------------
# 2. ДОСТУП К ДАННЫМ
# ------------------------------------------------------------
print("\n=== Доступ ===")

print(person["name"])          # Алексей — по ключу
# person["phone"]              # KeyError если ключа нет!

# Безопасный доступ через get() # получить значение по указанному ключу, если ключа нет — вернёт None (или значение по умолчанию)
print(person.get("age"))       # 25
print(person.get("phone"))     # None — не упадёт с ошибкой
print(person.get("phone", "не указан"))  # "не указан" — значение по умолчанию

# Проверка наличия ключа
print("name" in person)        # True
print("phone" in person)       # False


# ------------------------------------------------------------
# 3. ИЗМЕНЕНИЕ СЛОВАРЯ
# ------------------------------------------------------------
print("\n=== Изменение ===")

person["age"] = 26                      # изменить значение
person["email"] = "alex@example.com"   # добавить новый ключ
print(person)

# Обновление несколькими парами сразу
person.update({"city": "СПб", "phone": "+7-999-000"})
print(person)

# Удаление
del person["is_student"]                # удалить ключ
removed = person.pop("phone")           # удалить и вернуть значение
print(f"Удалили телефон: {removed}")
print(person)


# ------------------------------------------------------------
# 4. МЕТОДЫ СЛОВАРЯ
# ------------------------------------------------------------
print("\n=== Методы ===")

inventory = {"яблоки": 50, "бананы": 30, "вишня": 100}

print(inventory.keys())     # dict_keys(['яблоки', 'бананы', 'вишня'])
print(inventory.values())   # dict_values([50, 30, 100])
print(inventory.items())    # dict_items([('яблоки', 50), ...])

# Перебор словаря
for key in inventory:
    print(f"{key}: {inventory[key]}")

for key, value in inventory.items():    # удобнее!
    print(f"{key}: {value} шт.")

# setdefault — добавит ключ только если его нет
inventory.setdefault("манго", 0)
print(inventory)


# ------------------------------------------------------------
# 5. DICT COMPREHENSION
# ------------------------------------------------------------
print("\n=== Dict comprehension ===")

# Квадраты чисел
squares = {i: i**2 for i in range(1, 6)}
print(squares)    # {1: 1, 2: 4, 3: 9, 4: 16, 5: 25}

# Только чётные
even_squares = {i: i**2 for i in range(1, 11) if i % 2 == 0}
print(even_squares)

# Инвертировать словарь (поменять ключи и значения)
original = {"a": 1, "b": 2, "c": 3}
inverted = {v: k for k, v in original.items()}
print(inverted)    # {1: 'a', 2: 'b', 3: 'c'}


# ------------------------------------------------------------
# 6. ВЛОЖЕННЫЕ СЛОВАРИ
# ------------------------------------------------------------
print("\n=== Вложенные словари ===")

users = {
    "user1": {"name": "Анна", "age": 28, "score": 95},
    "user2": {"name": "Борис", "age": 34, "score": 82},
    "user3": {"name": "Вера", "age": 22, "score": 91},
}

# Доступ
print(users["user1"]["name"])     # Анна
print(users["user2"]["score"])    # 82

# Перебор
for user_id, data in users.items():
    print(f"{user_id}: {data['name']}, очки: {data['score']}")


# ------------------------------------------------------------
# 7. МНОЖЕСТВО (SET) — уникальные неупорядоченные элементы
# ------------------------------------------------------------
print("\n=== Множество ===")

# Создание
nums = {1, 2, 3, 4, 5}
from_list = set([1, 2, 2, 3, 3, 3, 4])   # дубликаты убираются автоматически
print(from_list)    # {1, 2, 3, 4}

# Добавление и удаление
nums.add(6)
nums.discard(1)     # удалить (не ошибка если нет)
nums.remove(2)      # удалить (ошибка если нет)
print(nums)

# Операции с множествами
a = {1, 2, 3, 4, 5}
b = {3, 4, 5, 6, 7}

print(a | b)    # объединение: {1, 2, 3, 4, 5, 6, 7}
print(a & b)    # пересечение: {3, 4, 5}
print(a - b)    # разность: {1, 2} — есть в a, нет в b
print(a ^ b)    # симметричная разность: {1, 2, 6, 7}

# Типичное применение: убрать дубликаты из списка
words = ["python", "java", "python", "c++", "java", "go"]
unique = list(set(words))
print(unique)


