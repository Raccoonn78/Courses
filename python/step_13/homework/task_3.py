# Абстрактный класс PaymentMethod(ABC):
#   - __init__(owner, balance)
#   - @abstractmethod pay(amount)    — выполнить платёж
#   - @abstractmethod refund(amount) — возврат средств
#   - @abstractmethod get_info()     — информация о методе оплаты
#   - Обычный метод check_balance()  — выводит текущий баланс
#   - @property balance              — только чтение
#
# Конкретные классы:
#
#   CreditCard(PaymentMethod):
#     - добавляет: card_number (последние 4 цифры), credit_limit
#     - pay: списывает с баланса (кредит включается если не хватает)
#     - refund: возвращает на баланс
#     - get_info: "Карта ****XXXX, лимит: N"
#
#   CryptoWallet(PaymentMethod):
#     - добавляет: currency ("BTC", "ETH" и т.д.), address
#     - pay: списывает с баланса, выводит transaction hash (random hex)
#     - refund: возвращает на баланс
#     - get_info: "Кошелёк [currency]: [address[:8]]..."
#
# PaymentMethod("X", 0) нельзя создать напрямую — покажи TypeError.
