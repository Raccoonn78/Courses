# @property:
#   - full_name   → "Имя Фамилия" (только чтение)
#   - age         → текущий год (2026) минус birth_year (только чтение)
#   - birth_year  → геттер + сеттер:
#                   сеттер проверяет: 1900 <= year <= 2026
#                   иначе raise ValueError
#
# Обычные атрибуты с валидацией через @property:
#   - first_name  → геттер + сеттер:
#                   сеттер проверяет что строка не пустая,
#                   сохраняет с заглавной буквы (capitalize)
#   - last_name   — аналогично
#
# Магические методы:
#   - __str__  → "Иван Иванов, 25 лет"
#   - __repr__ → "Person('Иван', 'Иванов', 2001)"
#
