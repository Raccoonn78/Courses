# ------------------------------------------------------------
# 1. АРИФМЕТИЧЕСКИЕ ОПЕРАТОРЫ
# ------------------------------------------------------------
a = 10
b = 3

print("=== Арифметика ===")
print(a + b)   # 13  — сложение
print(a - b)   # 7   — вычитание
print(a * b)   # 30  — умножение
print(a / b)   # 3.333... — деление (всегда float).  
print(a // b)  # 3   — целочисленное деление (без остатка)
print(a % b)   # 1   — остаток от деления
print(a ** b)  # 1000 — возведение в степень 


# ------------------------------------------------------------
# 2. ОПЕРАТОРЫ СРАВНЕНИЯ — возвращают True или False
# ------------------------------------------------------------
x = 5
y = 10

print("\n=== Сравнение ===")
print(x == y)   # False — равно
print(x != y)   # True  — не равно. 
print(x > y)    # False — больше
print(x < y)    # True  — меньше
print(x >= 5)   # True  — больше или равно
print(x <= 4)   # False — меньше или равно


# ------------------------------------------------------------
# 3. ЛОГИЧЕСКИЕ ОПЕРАТОРЫ
# ------------------------------------------------------------
# and — оба условия должны быть True
# or  — хотя бы одно условие True. 
# not — инвертирует значение

print("\n=== Логика ===")
print(True and True)   # True
print(True and False)  # False
print(False or True)   # True
print(False or False)  # False
print(not True)        # False
print(not False)       # True

# Практический пример: проверка диапазона
age = 20
is_adult = (age >= 18 and age <= 65)
print("Взрослый?", is_adult)  # True


# ------------------------------------------------------------
# 4. ОПЕРАТОРЫ ПРИСВАИВАНИЯ
# ------------------------------------------------------------
n = 10
print("\n=== Присваивание ===")

n += 5   # n = n + 5  → 15. 
print(n)

n -= 3   # n = n - 3  → 12
print(n)

n *= 2   # n = n * 2  → 24
print(n)

n //= 5  # n = n // 5 → 4
print(n)

n **= 3  # n = n ** 3 → 64
print(n)


# ------------------------------------------------------------
# 5. ПРИОРИТЕТ ОПЕРАТОРОВ (как в математике)
# ------------------------------------------------------------
# Порядок (от высшего к низшему):
#   ** → * / // % → + - → == != > < → not → and → or

print("\n=== Приоритет ===")
result = 2 + 3 * 4      # 14 (не 20! — сначала умножение)
print(result)

result = (2 + 3) * 4    # 20 — скобки меняют приоритет
print(result)

result = 10 > 5 and 3 < 7 or 3>10   # True and True → True
#
print(result)


