# ------------------------------------------------------------
# 1. ВЫВОД В КОНСОЛЬ
# ------------------------------------------------------------
# print() — функция для вывода информации в консоль

print("Hello, World!")             # строка
print(42)                          # число
print(3.14)                        # дробное число
print(True)                        # булевое значение
a=10
# Несколько значений через запятую
print("Ответ", a, sep='=')        # Ответ=10

one="один"
two="два"
three="три"
# Параметр sep — разделитель (по умолчанию пробел)
print(one, two, three, sep='-', end='\n')   # один-два-три

# Параметр end — что ставить в конце (по умолчанию \n — перенос строки)
print(one, end=";")
print(two, end=";")
print(three)                    # первый второй третий


# ------------------------------------------------------------
# 2. ПЕРЕМЕННЫЕ — именованная область памяти для хранения данных
# ------------------------------------------------------------
# Правила именования:
#   - только буквы, цифры, подчёркивание
#   - не может начинаться с цифры
#   - регистр важен: name ≠ Name ≠ NAME

a = 5
b = 10
c = 100
print(a)
print(b)
print(c)

# Несколько переменных в одну строку
x, y, z = 1, 2, 3
print(x, y, z)

# Одно значение нескольким переменным
p = q = r = 0
print(p, q, r)


# ------------------------------------------------------------
# 3. ТИПЫ ДАННЫХ
# ------------------------------------------------------------

# int — целое число
age = 25
year = 2026
negative = -42
print(age, year, negative)

# float — число с плавающей точкой (дробное)
height = 1.75
pi = 3.14159
temperature = -5.5
print(height, pi, temperature)

# str — строка (последовательность символов)
# Можно использовать одинарные, двойные или тройные кавычки
name = "Алексей"
greeting = 'Привет!'
multiline = """Это\nмногострочная\nстрока"""
multiline = """Это
многострочная
строка"""
print(name)
print(greeting)
print(multiline)

# bool — булевое значение (только True или False)
is_student = True
is_working = False
print(is_student)
print(is_working)

# None — отсутствие значения (пустота) # none — не None!
result = None
phone = None
print(result)   # None
print(phone)    # None


# ------------------------------------------------------------
# 4. ФУНКЦИЯ TYPE() — узнать тип переменной
# ------------------------------------------------------------

print("\n=== Типы переменных ===")
print(type(42))           # <class 'int'>
print(type(3.14))         # <class 'float'>
print(type("qwe"))        # <class 'str'>
print(type(True))         # <class 'bool'>
print(type(None))         # <class 'NoneType'>

# Проверка типа
x = 100
print(type(x) == int)     # True
print(isinstance(x, int)) # True — рекомендуемый способ


# ------------------------------------------------------------
# 5. ПРЕОБРАЗОВАНИЕ ТИПОВ (приведение)
# ------------------------------------------------------------
print("\n=== Преобразование типов ===")

# str → int
number_str = "42"
number_int = int(number_str)
print(number_int + 8)        # 50

# str → float
price_str = "99.99"
price_float = float(price_str)
print(price_float * 2)       # 199.98

# int → str
age_int = 25
age_str = str(age_int)
print("Мне " + age_str + " лет")   # конкатенация строк

# int → float и float → int
print(float(5))     # 5.0
print(int(3.99))    # 3 — дробная часть ОТБРАСЫВАЕТСЯ (не округляется!)

# bool ↔ int
print(int(True))    # 1
print(int(False))   # 0
print(bool(0))      # False
print(bool(1))      # True
print(bool(42))     # True
print(bool(""))     # False — пустая строка
print(bool("hi"))   # True


