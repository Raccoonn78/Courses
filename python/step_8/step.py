# ------------------------------------------------------------
# 1. ОПРЕДЕЛЕНИЕ ФУНКЦИИ
# ------------------------------------------------------------
# def — ключевое слово
# После определения функция не выполняется сама — её нужно ВЫЗВАТЬ

def greet():
    print("Привет, мир!")

greet()         # вызов
greet()         # можно вызывать сколько угодно раз


# ------------------------------------------------------------
# 2. ПАРАМЕТРЫ И АРГУМЕНТЫ
# ------------------------------------------------------------
# Параметры — имена в определении функции
# Аргументы — значения при вызове

def greet_person(name):            # name — параметр
    print(f"Привет, {name}!")

greet_person("Алексей")            # "Алексей" — аргумент
greet_person("Python")

# Несколько параметров
def add(a, b):
    result = a + b
    print(f"{a} + {b} = {result}")

add(3, 5)
add(10, 20)


# ------------------------------------------------------------
# 3. ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ
# ------------------------------------------------------------
# Если аргумент не передан, используется значение по умолчанию
# ВАЖНО: параметры с дефолтами должны идти ПОСЛЕ обязательных

def power(base, exponent=2):     # exponent по умолчанию = 2
    return base ** exponent

print(power(5))        # 25  — exponent = 2
print(power(5, 3))     # 125 — exponent = 3

# Именованные аргументы (keyword arguments)
def describe_person(name, age, city="Москва"):
    print(f"{name}, {age} лет, г. {city}")

describe_person("Анна", 28)
describe_person("Борис", 34, "Питер")
describe_person(age=22, name="Вера")          # можно менять порядок


# ------------------------------------------------------------
# 4. ВОЗВРАЩАЕМЫЕ ЗНАЧЕНИЯ
# ------------------------------------------------------------
def add_numbers(a, b):
    return a + b               # функция ВОЗВРАЩАЕТ значение

result = add_numbers(10, 5)    # сохраняем результат в переменную
print(result)

# Возврат нескольких значений (на самом деле кортеж)
def min_max(numbers):
    return min(numbers), max(numbers)

minimum, maximum = min_max([3, 1, 4, 1, 5, 9, 2, 6])
print(f"Мин: {minimum}, Макс: {maximum}")

# Ранний выход из функции
def check_positive(n):
    if n < 0:
        return "Отрицательное"
    if n == 0:
        return "Ноль"
    return "Положительное"

print(check_positive(-5))
print(check_positive(0))
print(check_positive(42))


# ------------------------------------------------------------
# 5. *ARGS — произвольное количество позиционных аргументов
# ------------------------------------------------------------
def sum_all(*args):
    # args — это кортеж всех переданных аргументов
    print(f"Получили: {args}")
    return sum(args)

print(sum_all(1, 2, 3))           # 6
print(sum_all(10, 20, 30, 40))    # 100

def greet_all(greeting, *names):
    for name in names:
        print(f"{greeting}, {name}!")

greet_all("Привет", "Анна", "Борис", "Вера")


# ------------------------------------------------------------
# 6. **KWARGS — произвольное количество именованных аргументов
# ------------------------------------------------------------
def create_profile(**kwargs):
    # kwargs — словарь всех именованных аргументов
    for key, value in kwargs.items():
        print(f"  {key}: {value}")

print("\nПрофиль:")
create_profile(name="Алексей", age=25, city="Москва", hobby="Python")

# Комбинация всех видов параметров
def full_example(required, default="нет", *args, **kwargs):
    print(f"required={required}")
    print(f"default={default}")
    print(f"args={args}")
    print(f"kwargs={kwargs}")

full_example("обязательный", "дефолт", 1, 2, 3, x=10, y=20)


# ------------------------------------------------------------
# 7. ОБЛАСТЬ ВИДИМОСТИ (SCOPE)
# ------------------------------------------------------------
# Переменные внутри функции — ЛОКАЛЬНЫЕ, снаружи не видны
# Переменные снаружи — ГЛОБАЛЬНЫЕ, внутри видны (но не изменяются)

global_var = "я глобальная"

def scope_example():
    local_var = "я локальная"
    print(global_var)       # видим глобальную
    print(local_var)

scope_example()
print(global_var)
# print(local_var)          # NameError — локальная недоступна снаружи

# global — изменить глобальную переменную из функции (использовать осторожно)
counter = 0

def increment():
    global counter
    counter += 1

increment()
increment()
print(counter)    # 2


# ------------------------------------------------------------
# 8. LAMBDA — анонимная функция в одну строку
# ------------------------------------------------------------
# Синтаксис: lambda параметры: выражение

square = lambda x: x ** 2
print(square(5))    # 25

add = lambda a, b: a + b
print(add(3, 7))    # 10

# Главное применение — как аргумент для sorted, map, filter
numbers = [5, 2, 8, 1, 9, 3]
sorted_nums = sorted(numbers, key=lambda x: -x)  # по убыванию
print(sorted_nums)

students = [("Анна", 95), ("Борис", 82), ("Вера", 91)]
by_score = sorted(students, key=lambda s: s[1], reverse=True)
print(by_score)

# map — применить функцию к каждому элементу
squared = list(map(lambda x: x**2, [1, 2, 3, 4, 5]))
print(squared)

# filter — отфильтровать элементы
evens = list(filter(lambda x: x % 2 == 0, range(1, 11)))
print(evens)


