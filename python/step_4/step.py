# ------------------------------------------------------------
# 1. БАЗОВЫЙ СИНТАКСИС if / elif / else
# ------------------------------------------------------------
# ВАЖНО: Python использует ОТСТУПЫ (4 пробела) вместо фигурных скобок!

score = 75

if score >= 90:
    print("Отлично")
elif score >= 75:
    print("Хорошо")      # <-- выполнится это
elif score >= 60:
    print("Удовлетворительно")
else:
    print("Неудовлетворительно")


# ------------------------------------------------------------
# 2. УСЛОВИЯ СО СТРОКАМИ И БУЛЕВЫМИ ЗНАЧЕНИЯМИ
# ------------------------------------------------------------
is_logged_in = True
username = "admin"

if is_logged_in:
    print(f"Добро пожаловать, {username}!")
else:
    print("Пожалуйста, войдите в систему.")

# Проверка на пустоту
name = ""
if name:              # пустая строка == False
    print(f"Привет, {name}")
else:
    print("Имя не введено")


# ------------------------------------------------------------
# 3. КОМБИНИРОВАНИЕ УСЛОВИЙ (and, or, not)
# ------------------------------------------------------------
age = 20
has_ticket = True

print("\n=== Комбинирование ===")

if age >= 18 and has_ticket:
    print("Вход разрешён")

if age < 10 or age > 65:
    print("Льготный билет")
else:
    print("Полная стоимость")   # <-- выполнится

if not has_ticket:
    print("Купи билет")
else:
    print("Билет есть!")        # <-- выполнится


# ------------------------------------------------------------
# 4. ВЛОЖЕННЫЕ УСЛОВИЯ
# ------------------------------------------------------------
# Лучше избегать глубокой вложенности, но знать нужно

hour = 14

print("\n=== Вложенные условия ===")
if hour < 12:
    print("Утро")
    if hour < 6:
        print("Слишком рано!")
else:
    if hour < 18:
        print("День")       # <-- выполнится
    elif hour < 22:
        print("Вечер")
    else:
        print("Ночь")


# ------------------------------------------------------------
# 5. ОПЕРАТОР IN — проверка вхождения
# ------------------------------------------------------------
fruits = ["яблоко", "банан", "вишня"]
choice = "банан"

print("\n=== Оператор in ===")
if choice in fruits:
    print(f"{choice} есть в списке")

# Также работает со строками
email = "user@example.com"
if "@" in email:
    print("Похоже на email")


# ------------------------------------------------------------
# 6. ТЕРНАРНЫЙ ОПЕРАТОР (однострочное условие)
# ------------------------------------------------------------
# значение_если_true  if  условие  else  значение_если_false

print("\n=== Тернарный оператор ===")
temperature = 25
weather = "тепло" if temperature > 20 else "холодно"
print(f"За окном {weather}")

number = -7
absolute = number if number >= 0 else -number
print(f"Модуль числа {number} = {absolute}")


# ------------------------------------------------------------
# 7. MATCH (Python 3.10+) — аналог switch/case
# ------------------------------------------------------------
day = "Понедельник"

print("\n=== Match ===")
match day:
    case "Суббота" | "Воскресенье":
        print("Выходной!")
    case "Понедельник":
        print("Начало рабочей недели")   # <-- выполнится
    case "Пятница":
        print("Почти выходной!")
    case _:                              # default — любое другое значение
        print("Обычный рабочий день")


